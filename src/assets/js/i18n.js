export function keys(lang) {
  return Object.keys(STRINGS[lang] ?? {});
}

export function t(lang, key, params = {}) {
  const template = STRINGS[lang]?.[key] ?? STRINGS.pl[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}

export function formatMoney(value, lang) {
  return new Intl.NumberFormat(LOCALE[lang], {
    style: 'currency', currency: CURRENCY[lang], minimumFractionDigits: 0, maximumFractionDigits: 0,
  }).format(value);
}

export function formatLength(value, lang) {
  return `${new Intl.NumberFormat(LOCALE[lang], { minimumFractionDigits: 1, maximumFractionDigits: 2 }).format(value)} m`;
}
